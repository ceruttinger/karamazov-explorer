(function () {
  "use strict";

  const BK = window.BK || {};

  let concepts = [];
  let passages = [];
  let characters = [];
  let chapters = [];

  let selectedConcepts = new Set();
  let selectedChapter = "";
  let selectedCharacter = "";

  function esc(v) {
    return BK.escapeHTML
      ? BK.escapeHTML(v)
      : String(v ?? "")
          .replaceAll("&", "&amp;")
          .replaceAll("<", "&lt;")
          .replaceAll(">", "&gt;")
          .replaceAll('"', "&quot;");
  }

  function cutoff() {
    return BK.getReaderPosition
      ? BK.getReaderPosition()
      : Number.MAX_SAFE_INTEGER;
  }

  function allowed(position) {
    if (position === null || position === undefined || position === "") {
      return true;
    }
    return Number(position) <= cutoff();
  }

  function shortName(name) {
    return String(name || "")
      .replace("Fyodorovich ", "")
      .replace("Pavlovich ", "");
  }

  function conceptById(id) {
    return concepts.find(c => c.concept_id === id);
  }

  function characterByIdOrName(value) {
    return characters.find(c =>
      c.entity_id === value ||
      c.canonical_name === value
    );
  }

  function chapterKey(obj) {
    return `${obj.part}|${obj.book}|${obj.chapter}`;
  }

  function chapterLabel(obj) {
    return `Part ${obj.part} · Book ${obj.book} · Chapter ${obj.chapter}`;
  }

  function visibleChapters() {
    return chapters.filter(c =>
      allowed(c.max_narrative_position)
    );
  }

  function visiblePassages() {
    return passages.filter(p =>
      allowed(p.narrative_position)
    );
  }

  function selectedConceptObjects() {
    return [...selectedConcepts]
      .map(conceptById)
      .filter(Boolean);
  }

  /*
   * concepts_v2.json already contains the authoritative
   * chapter trajectory generated by our build process.
   */
  function visibleTrajectory(concept) {
    return (concept.trajectory || [])
      .filter(row =>
        allowed(row.first_narrative_position)
      )
      .map(row => {
        const chapter = chapters.find(c =>
          String(c.part) === String(row.part) &&
          String(c.book) === String(row.book) &&
          String(c.chapter) === String(row.chapter)
        );

        return {
          ...row,
          chapter_order:
            chapter?.chapter_order ?? 0,
          chapter_title:
            chapter?.chapter_title ?? "",
          max_narrative_position:
            chapter?.max_narrative_position ??
            row.first_narrative_position
        };
      })
      .filter(row =>
        allowed(row.max_narrative_position)
      )
      .sort((a, b) =>
        Number(a.chapter_order) -
        Number(b.chapter_order)
      );
  }

  /*
   * passage_index.json concept values may be strings or
   * objects. Normalize both representations.
   */
  function passageConceptNames(passage) {
    const raw = passage.concepts || [];

    if (!Array.isArray(raw)) return [];

    return raw.map(item => {
      if (typeof item === "string") {
        return item;
      }

      return (
        item.concept_name ||
        item.name ||
        item.concept_id ||
        ""
      );
    }).filter(Boolean);
  }

  function passageHasConcept(passage, concept) {
    const names =
      passageConceptNames(passage)
        .map(x => String(x).toLowerCase());

    return (
      names.includes(
        String(concept.concept_name).toLowerCase()
      ) ||
      names.includes(
        String(concept.concept_id).toLowerCase()
      )
    );
  }

  function passageCharacterNames(passage) {
    return Array.isArray(passage.entities_mentioned)
      ? passage.entities_mentioned
      : [];
  }

  function renderPills() {
    const target =
      document.getElementById("bk-theme-pills");

    if (!target) return;

    target.innerHTML = concepts.map(concept => `
      <label class="bk-theme-pill">
        <input
          type="checkbox"
          value="${esc(concept.concept_id)}"
          ${selectedConcepts.has(concept.concept_id)
            ? "checked"
            : ""}
        >
        <span>${esc(concept.concept_name)}</span>
      </label>
    `).join("");

    target
      .querySelectorAll('input[type="checkbox"]')
      .forEach(input => {
        input.addEventListener("change", () => {
          if (input.checked) {
            selectedConcepts.add(input.value);
          } else {
            selectedConcepts.delete(input.value);
          }

          selectedChapter = "";
          renderEverything();
        });
      });
  }

  function renderStatus() {
    const target =
      document.getElementById("bk-theme-status");

    if (!target) return;

    const selected =
      selectedConceptObjects();

    if (!selected.length) {
      target.innerHTML = `
        <strong>No concepts selected</strong>
        <span>
          Select one or more concepts above.
        </span>
      `;
      return;
    }

    target.innerHTML = `
      <strong>
        ${esc(
          selected
            .map(c => c.concept_name)
            .join(" · ")
        )}
      </strong>

      <span>
        ${visibleChapters().length}
        chapters visible at your reader position
      </span>
    `;
  }

  function renderChart() {
    const target =
      document.getElementById("bk-theme-chart");

    if (!target || !window.Plotly) return;

    const selected =
      selectedConceptObjects();

    if (!selected.length) {
      Plotly.purge(target);

      target.innerHTML = `
        <div class="bk-chart-empty">
          Select one or more concepts to compare
          their trajectory through the novel.
        </div>
      `;
      return;
    }

    const measure =
      document.getElementById("bk-theme-measure")
        ?.value || "passages";

    const traces =
      selected.map(concept => {
        const rows =
          visibleTrajectory(concept);

        return {
          type: "scatter",
          mode: "lines+markers",

          name:
            concept.concept_name,

          x:
            rows.map(
              row => row.chapter_order
            ),

          y:
            rows.map(
              row =>
                Number(
                  row[measure] || 0
                )
            ),

          customdata:
            rows.map(
              row =>
                chapterKey(row)
            ),

          text:
            rows.map(row =>
              `${chapterLabel(row)}` +
              (
                row.chapter_title
                  ? `<br>${row.chapter_title}`
                  : ""
              )
            ),

          hovertemplate:
            "%{text}<br>" +
            (
              measure === "matches"
                ? "Term matches: "
                : "Passages: "
            ) +
            "%{y}" +
            "<extra>%{fullData.name}</extra>"
        };
      });

    Plotly.newPlot(
      target,
      traces,
      {
        margin: {
          l: 60,
          r: 25,
          t: 45,
          b: 60
        },

        hovermode: "closest",

        xaxis: {
          title: "Chapter progression",
          rangemode: "tozero"
        },

        yaxis: {
          title:
            measure === "matches"
              ? "Term matches"
              : "Concept-bearing passages",
          rangemode: "tozero"
        },

        legend: {
          orientation: "h",
          y: 1.12
        }
      },
      {
        responsive: true,
        displaylogo: false
      }
    );

    target.on("plotly_click", event => {
      const point =
        event?.points?.[0];

      if (!point) return;

      selectedChapter =
        String(point.customdata || "");

      const select =
        document.getElementById(
          "bk-theme-chapter-filter"
        );

      if (select) {
        select.value =
          selectedChapter;
      }

      renderEvidence();
    });
  }

  function conceptPassages(concept) {
    return visiblePassages()
      .filter(p =>
        passageHasConcept(
          p,
          concept
        )
      );
  }

  function conceptCharacterCounts(concept) {
    const counts = new Map();

    conceptPassages(concept)
      .forEach(passage => {
        const unique =
          new Set(
            passageCharacterNames(
              passage
            )
          );

        unique.forEach(name => {
          const character =
            characterByIdOrName(name);

          if (!character) return;

          counts.set(
            character.entity_id,
            (
              counts.get(
                character.entity_id
              ) || 0
            ) + 1
          );
        });
      });

    return [...counts.entries()]
      .map(([id, count]) => ({
        character:
          characters.find(
            c => c.entity_id === id
          ),
        count
      }))
      .filter(x => x.character)
      .sort(
        (a, b) =>
          b.count - a.count
      );
  }

  function renderInspector() {
    const target =
      document.getElementById(
        "bk-theme-detail"
      );

    if (!target) return;

    const selected =
      selectedConceptObjects();

    if (!selected.length) {
      target.innerHTML = `
        <div class="bk-detail-placeholder">

          <div class="bk-eyebrow">
            CONCEPT INSPECTOR
          </div>

          <h3>Select a concept</h3>

          <p>
            Choose a concept to inspect its
            trajectory, associated characters,
            strongest chapters, and evidence.
          </p>

        </div>
      `;
      return;
    }

    if (selected.length > 1) {
      target.innerHTML = `
        <div class="bk-eyebrow">
          COMPARISON MODE
        </div>

        <h2>
          ${selected.length}
          concepts selected
        </h2>

        <p class="bk-panel-help">
          The trajectory chart compares the selected
          concepts. Select one below to inspect it
          individually.
        </p>

        <div class="bk-theme-comparison-list">

          ${selected.map(concept => `
            <button
              class="bk-theme-comparison-item"
              type="button"
              data-concept="${esc(
                concept.concept_id
              )}"
            >
              <strong>
                ${esc(
                  concept.concept_name
                )}
              </strong>

              <span>
                ${conceptPassages(concept).length}
                visible passages
              </span>
            </button>
          `).join("")}

        </div>
      `;

      target
        .querySelectorAll(
          ".bk-theme-comparison-item"
        )
        .forEach(button => {
          button.addEventListener(
            "click",
            () => {
              selectedConcepts =
                new Set([
                  button.dataset.concept
                ]);

              selectedChapter = "";
              selectedCharacter = "";

              renderPills();
              renderEverything();
            }
          );
        });

      return;
    }

    const concept =
      selected[0];

    const trajectory =
      visibleTrajectory(concept);

    const conceptPassageList =
      conceptPassages(concept);

    const charactersForConcept =
      conceptCharacterCounts(concept);

    const strongest =
      [...trajectory]
        .sort(
          (a, b) =>
            Number(b.passages) -
            Number(a.passages)
        )
        .slice(0, 10);

    target.innerHTML = `
      <div class="bk-eyebrow">
        CONCEPT SIGNAL
      </div>

      <h2>
        ${esc(concept.concept_name)}
      </h2>

      <p class="bk-theme-definition">
        ${esc(
          concept.definition ||
          "Computationally identified lexical concept."
        )}
      </p>

      <div class="bk-theme-stat-grid">

        <div>
          <strong>
            ${conceptPassageList.length}
          </strong>
          <span>visible passages</span>
        </div>

        <div>
          <strong>
            ${trajectory.length}
          </strong>
          <span>visible chapters</span>
        </div>

        <div>
          <strong>
            ${charactersForConcept.length}
          </strong>
          <span>characters</span>
        </div>

      </div>

      <h3>Detection terms</h3>

      <div class="bk-theme-terms">
        ${(concept.terms || [])
          .map(term =>
            `<span>${esc(term)}</span>`
          )
          .join("")}
      </div>

      <h3>
        Characters in concept passages
      </h3>

      <div class="bk-theme-character-bars">

        ${
          charactersForConcept.length
            ? charactersForConcept
                .slice(0, 12)
                .map(row => `
                  <button
                    class="bk-theme-character-row"
                    type="button"
                    data-character="${esc(
                      row.character.entity_id
                    )}"
                  >
                    <span>
                      ${esc(
                        shortName(
                          row.character.canonical_name
                        )
                      )}
                    </span>

                    <strong>
                      ${row.count}
                    </strong>
                  </button>
                `)
                .join("")
            : `
              <p class="bk-muted">
                No visible character associations.
              </p>
            `
        }

      </div>

      <h3>Strongest chapters</h3>

      <div class="bk-theme-chapter-list">

        ${strongest.map(row => `
          <button
            class="bk-theme-chapter-row"
            type="button"
            data-chapter="${esc(
              chapterKey(row)
            )}"
          >
            <span>
              ${esc(
                chapterLabel(row)
              )}
            </span>

            <strong>
              ${row.passages}
            </strong>
          </button>
        `).join("")}

      </div>
    `;

    target
      .querySelectorAll(
        ".bk-theme-character-row"
      )
      .forEach(button => {
        button.addEventListener(
          "click",
          () => {
            selectedCharacter =
              button.dataset.character;

            const select =
              document.getElementById(
                "bk-theme-character-filter"
              );

            if (select) {
              select.value =
                selectedCharacter;
            }

            renderEvidence();
          }
        );
      });

    target
      .querySelectorAll(
        ".bk-theme-chapter-row"
      )
      .forEach(button => {
        button.addEventListener(
          "click",
          () => {
            selectedChapter =
              button.dataset.chapter;

            const select =
              document.getElementById(
                "bk-theme-chapter-filter"
              );

            if (select) {
              select.value =
                selectedChapter;
            }

            renderEvidence();
          }
        );
      });
  }

  function populateFilters() {
    const characterSelect =
      document.getElementById(
        "bk-theme-character-filter"
      );

    if (characterSelect) {
      characterSelect.innerHTML =
        '<option value="">All characters</option>';

      characters
        .filter(c =>
          allowed(
            c.first_narrative_position
          )
        )
        .sort(
          (a, b) =>
            a.canonical_name.localeCompare(
              b.canonical_name
            )
        )
        .forEach(character => {
          const option =
            document.createElement(
              "option"
            );

          option.value =
            character.entity_id;

          option.textContent =
            character.canonical_name;

          option.selected =
            character.entity_id ===
            selectedCharacter;

          characterSelect.appendChild(
            option
          );
        });
    }

    const chapterSelect =
      document.getElementById(
        "bk-theme-chapter-filter"
      );

    if (chapterSelect) {
      chapterSelect.innerHTML =
        '<option value="">All visible chapters</option>';

      visibleChapters()
        .sort(
          (a, b) =>
            Number(a.chapter_order) -
            Number(b.chapter_order)
        )
        .forEach(chapter => {
          const option =
            document.createElement(
              "option"
            );

          option.value =
            chapterKey(chapter);

          option.textContent =
            `${chapterLabel(chapter)}` +
            (
              chapter.chapter_title
                ? ` — ${chapter.chapter_title}`
                : ""
            );

          option.selected =
            option.value ===
            selectedChapter;

          chapterSelect.appendChild(
            option
          );
        });
    }
  }

  function evidencePassages() {
    const selected =
      selectedConceptObjects();

    if (!selected.length) return [];

    return visiblePassages()
      .filter(passage =>
        selected.some(concept =>
          passageHasConcept(
            passage,
            concept
          )
        )
      )
      .filter(passage =>
        !selectedChapter ||
        chapterKey(passage) ===
          selectedChapter
      )
      .filter(passage => {
        if (!selectedCharacter) {
          return true;
        }

        const character =
          characters.find(
            c =>
              c.entity_id ===
              selectedCharacter
          );

        if (!character) return false;

        return passageCharacterNames(
          passage
        ).includes(
          character.canonical_name
        );
      })
      .sort(
        (a, b) =>
          Number(a.narrative_position) -
          Number(b.narrative_position)
      );
  }

  function renderEvidence() {
    const target =
      document.getElementById(
        "bk-theme-evidence"
      );

    if (!target) return;

    if (!selectedConcepts.size) {
      target.innerHTML = `
        <div class="bk-empty-state">
          Select a concept to view its
          supporting passages.
        </div>
      `;
      return;
    }

    const results =
      evidencePassages();

    if (!results.length) {
      target.innerHTML = `
        <div class="bk-empty-state">
          No passages match the current
          concept, chapter, character, and
          reader-position filters.
        </div>
      `;
      return;
    }

    const shown =
      results.slice(0, 40);

    target.innerHTML = `
      <div class="bk-evidence-result-count">
        Showing ${shown.length} of
        ${results.length} matching passages
      </div>

      <div class="bk-theme-passage-grid">

        ${shown.map(passage => {

          const matchedConcepts =
            selectedConceptObjects()
              .filter(concept =>
                passageHasConcept(
                  passage,
                  concept
                )
              );

          return `
            <article
              class="bk-theme-passage-card"
            >

              <div
                class="bk-theme-passage-location"
              >
                ${esc(
                  passage.citation_label ||
                  chapterLabel(passage)
                )}
              </div>

              <p
                class="bk-theme-passage-text"
              >
                ${esc(passage.text)}
              </p>

              <div
                class="bk-theme-passage-tags"
              >

                ${matchedConcepts
                  .map(concept => `
                    <span
                      class="bk-theme-tag"
                    >
                      ${esc(
                        concept.concept_name
                      )}
                    </span>
                  `)
                  .join("")}

                ${passageCharacterNames(
                  passage
                )
                  .map(name => `
                    <span
                      class="bk-character-tag"
                    >
                      ${esc(
                        shortName(name)
                      )}
                    </span>
                  `)
                  .join("")}

              </div>

              <div
                class="bk-theme-passage-id"
              >
                ${esc(
                  passage.passage_id
                )}
              </div>

            </article>
          `;
        }).join("")}

      </div>
    `;
  }

  function renderEverything() {
    populateFilters();
    renderStatus();
    renderChart();
    renderInspector();
    renderEvidence();
  }

  function wireControls() {
    document
      .getElementById(
        "bk-theme-clear"
      )
      ?.addEventListener(
        "click",
        () => {
          selectedConcepts.clear();
          selectedChapter = "";
          selectedCharacter = "";

          renderPills();
          renderEverything();
        }
      );

    document
      .getElementById(
        "bk-theme-all"
      )
      ?.addEventListener(
        "click",
        () => {
          selectedConcepts =
            new Set(
              concepts.map(
                c => c.concept_id
              )
            );

          selectedChapter = "";
          selectedCharacter = "";

          renderPills();
          renderEverything();
        }
      );

    document
      .getElementById(
        "bk-theme-measure"
      )
      ?.addEventListener(
        "change",
        renderChart
      );

    document
      .getElementById(
        "bk-theme-character-filter"
      )
      ?.addEventListener(
        "change",
        event => {
          selectedCharacter =
            event.target.value;

          renderEvidence();
        }
      );

    document
      .getElementById(
        "bk-theme-chapter-filter"
      )
      ?.addEventListener(
        "change",
        event => {
          selectedChapter =
            event.target.value;

          renderEvidence();
        }
      );
  }

  function readerPositionChanged() {
    selectedChapter = "";
    selectedCharacter = "";

    renderEverything();
  }

  async function initialize() {
    const target =
      document.getElementById(
        "bk-theme-pills"
      );

    if (!target) return;

    try {
      [
        concepts,
        passages,
        characters,
        chapters
      ] = await Promise.all([
        BK.fetchJSON(
          "data/public/concepts_v2.json"
        ),
        BK.fetchJSON(
          "data/public/passage_index.json"
        ),
        BK.fetchJSON(
          "data/public/characters_v2.json"
        ),
        BK.fetchJSON(
          "data/public/chapters_v2.json"
        )
      ]);

      console.log(
        "Themes v2 data loaded:",
        {
          concepts: concepts.length,
          passages: passages.length,
          characters: characters.length,
          chapters: chapters.length
        }
      );

      if (concepts.length) {
        selectedConcepts.add(
          concepts[0].concept_id
        );
      }

      renderPills();
      wireControls();
      renderEverything();

      window.addEventListener(
        "bk-reader-position-changed",
        readerPositionChanged
      );

    } catch (error) {
      console.error(
        "Themes v2 initialization failed:",
        error
      );

      target.innerHTML = `
        <div class="bk-error">
          Themes could not be initialized:
          ${esc(error.message)}
        </div>
      `;
    }
  }

  if (
    document.readyState ===
    "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      initialize
    );
  } else {
    initialize();
  }

})();
